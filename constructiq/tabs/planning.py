"""Tab 3: Planning & Real Estate Valuation."""
import streamlit as st

from .. import styles, ui
from ..services import valuation as v


def render() -> None:
    st.subheader("Planning & Real Estate Valuation")
    st.caption("Indicative budget, material and asset-value estimates in INR. "
               "Rates are planning assumptions, not quotations.")

    c1, c2 = st.columns(2)
    structure = c1.selectbox("Structure type", v.STRUCTURE_TYPES)
    sqft = c2.number_input("Built-up area (sq ft)", min_value=100, max_value=1_000_000,
                           value=2400, step=100)
    tier = c1.selectbox("Location tier", v.TIERS, help="Tier 1 = metros, Tier 3 = smaller towns")
    c1.caption(v.TIER_HELP[tier])
    completion = c2.slider("Completion (%)", 0, 100, 40)

    try:
        est = v.estimate(structure, sqft, tier, completion)
    except ValueError as exc:
        styles.notice(str(exc), "bad")
        return

    row1 = st.columns(3)
    row1[0].markdown(styles.metric("Total project budget", v.format_inr(est["total_budget_inr"]),
                                   "incl. 8% contingency"), unsafe_allow_html=True)
    row1[1].markdown(styles.metric("Capex incurred", v.format_inr(est["capex_incurred_inr"]),
                                   f"{completion}% of budget"), unsafe_allow_html=True)
    row1[2].markdown(styles.metric("Current market value", v.format_inr(est["current_market_value_inr"]),
                                   f"completed: {v.format_inr(est['completed_asset_value_inr'])}"),
                     unsafe_allow_html=True)

    st.write("")
    row2 = st.columns(3)
    row2[0].markdown(styles.metric("Cement required", f"{est['cement_bags_total']:,} bags",
                                   f"≈ {est['cement_tonnes_total']} t | used so far {est['cement_bags_used']:,}"),
                     unsafe_allow_html=True)
    row2[1].markdown(styles.metric("Steel required", f"{est['steel_tonnes_total']} t",
                                   f"used so far {est['steel_tonnes_used']} t"), unsafe_allow_html=True)
    row2[2].markdown(styles.metric("Balance to spend", v.format_inr(est["balance_to_spend_inr"])),
                     unsafe_allow_html=True)

    st.markdown("#### Milestone progress")
    st.progress(completion / 100, text=f"{completion}% complete: {est['milestone']}")
    for name, start, end in v.MILESTONES:
        if completion >= end:
            tag = styles.pill("Done", "ok")
        elif completion >= start:
            tag = styles.pill("In progress", "medium")
        else:
            tag = styles.pill("Upcoming", "neutral")
        st.markdown(f"{tag} &nbsp;**{name}** ({start}–{end}%)", unsafe_allow_html=True)

    with st.expander("Assumptions used"):
        st.markdown(
            f"- Build cost: ₹{v.BUILD_RATE[structure]:,}/sq ft (Tier 2 baseline) × "
            f"{v.TIER_COST_FACTOR[tier]} tier factor, plus {int(v.CONTINGENCY * 100)}% contingency\n"
            f"- Completed market value: ₹{v.MARKET_RATE[tier][structure]:,}/sq ft\n"
            f"- Land counted as {int(v.LAND_SHARE * 100)}% of completed value from day one; "
            "the rest accrues with completion\n"
            f"- Cement ≈ {v.CEMENT_BAGS_PER_SQFT} bags (50 kg)/sq ft; steel ≈ "
            f"{v.STEEL_KG_PER_SQFT[structure]} kg/sq ft\n"
            "- Material use is assumed to track completion in a straight line")

    st.markdown("#### Conceptual 3D rendering")
    prompt = st.text_area("Rendering prompt (editable)",
                          v.rendering_prompt(structure, tier, sqft, completion), height=90)
    if st.button("Generate rendering with Pollinations AI"):
        st.session_state["render_url"] = v.pollinations_url(prompt)
    url = st.session_state.get("render_url")
    if url:
        st.image(url, caption="AI-generated concept image, not a design drawing")
        st.caption("Generated by the external Pollinations service. It may be slow or unavailable.")
        st.markdown(f"[Open image in a new tab]({url})")

    ui.json_download(est, "planning_valuation_estimate.json", "Download estimate (JSON)")
